#!/usr/bin/env python3
"""Publication-intent V24 synthetic controlled-world and error figures.

These visualize only synthetic images generated by the V24 code.
They do NOT visualize or imply real CRACKS geology or actual trained
ANZA-LIRA segmentation. Labels and scores annotate the scene after evaluation.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from scripts.tver_v24_switched_neighbor_synthetic import (
    BASE,N,render_hard_v24,
)


def plot_three_worlds(index,out):
    scenes=render_hard_v24(index)
    fig,axes=plt.subplots(3,3,figsize=(11.2,9.0),dpi=120,
                          gridspec_kw={"wspace":.04,"hspace":.06})
    limits=np.concatenate([np.stack(
        (s["adjacent"][0],s["central"],s["adjacent"][1])).ravel()
        for s in scenes])
    vmin,vmax=np.quantile(limits,[.015,.995])
    for i,s in enumerate(scenes):
        layers=[s["adjacent"][0],s["central"],s["adjacent"][1]]
        for j,layer in enumerate(layers):
            ax=axes[i,j]
            ax.imshow(layer,cmap="gray",interpolation="nearest",
                      vmin=vmin,vmax=vmax,origin="upper")
            ax.set_xticks([]);ax.set_yticks([])
            ax.set_xlim(4,60);ax.set_ylim(59,4)
            if j==1:
                sx,sy=s["source"]
                ax.scatter([sx],[sy],s=36,facecolors="none",
                           edgecolors="#D93636",linewidths=1.3)
                for k,(x,y) in enumerate(s["candidates"]):
                    ax.scatter([x],[y],s=28,facecolors="none",
                               edgecolors="#227BC0",linewidths=1.1)
                    ax.text(x-1.5,y-2.,str(k),color="#227BC0",fontsize=7,
                            ha="center")
            if i==0:
                ax.set_title(("z = -1","z = 0","z = +1")[j],fontsize=13)
            if j==0:
                label=("LINK: candidate "+str(s["label"])
                       if s["label"]!=2 else
                       "NO_LINK (switched neighbors)")
                ax.set_ylabel(label,fontsize=11,labelpad=12)
    fig.suptitle(
        "V24 — same central image, different cross-slice connectivity",
        fontsize=15,y=.995)
    fig.text(.5,.014,
             "Artificial Gaussian traces with provided endpoints; not observed seismic data.",
             ha="center",fontsize=9)
    out.parent.mkdir(parents=True,exist_ok=True)
    fig.savefig(out,dpi=300,bbox_inches="tight")
    plt.close(fig)


def plot_error(cases,out):
    with cases.open(newline="",encoding="utf8") as f:
        rows=list(csv.DictReader(f))
    bad=[r for r in rows if
         int(r["label"])==2 and int(r["consensus_v24_pred"])!=2]
    if not bad:
        # Keep report truthful and no invented failure panel.
        return {"case_count":0,"status":"NO_FALSE_ACCEPTS_IN_REGISTERED_TEST"}
    r=bad[0]
    idx=int(r["base"])-BASE
    if not 0<=idx<N:
        raise RuntimeError("Error manifest references an unknown V24 scene")
    source=render_hard_v24(idx)[2]
    fig,axes=plt.subplots(1,3,figsize=(11.2,3.8),dpi=120)
    layers=[source["adjacent"][0],source["central"],source["adjacent"][1]]
    lo,hi=np.quantile(np.stack(layers),[.015,.995])
    for j,(ax,image) in enumerate(zip(axes,layers)):
        ax.imshow(image,cmap="gray",origin="upper",
                  interpolation="nearest",vmin=lo,vmax=hi)
        ax.set_xticks([]);ax.set_yticks([])
        ax.set_title(("z=-1","z=0","z=+1")[j])
    fig.suptitle(
        f"V24 registered error: true NO_LINK, accepted candidate {r['consensus_v24_pred']}",
        fontsize=13)
    fig.text(.5,.02,
             "Synthetic, oracle candidate positions. False acceptance is retained, not repaired.",
             ha="center",fontsize=9)
    out.parent.mkdir(parents=True,exist_ok=True)
    fig.savefig(out,dpi=300,bbox_inches="tight")
    plt.close(fig)
    return {"status":"REAL_REGISTERED_SYNTHETIC_ERROR_PLOTTED",
            "case_count":len(bad),"base":int(r["base"]),
            "true_label":int(r["label"]),
            "selected":int(r["consensus_v24_pred"])}


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--cases",required=True,type=Path)
    p.add_argument("--out",required=True,type=Path)
    args=p.parse_args()
    plot_three_worlds(0,args.out/"V24_three_worlds.png")
    receipt=plot_error(args.cases,args.out/"V24_failure_case.png")
    import json
    (args.out/"V24_figure_receipt.json").write_text(
        json.dumps(receipt,indent=2)+"\n")
    print(receipt)


if __name__=="__main__":
    main()
