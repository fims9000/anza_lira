#!/usr/bin/env python3
"""Run real S112 photometric bead-candidate detector across EVERY original H50Z tile.

This is NOT trained ANZA, and is NOT S111 global particle linking. The source
mask on new tiles is generated by black-hat, NOT the historical S88 annotation.
Outputs private per-tile evidence for operator review, never expert ground truth.
"""
from __future__ import annotations
import argparse,json,sys
from pathlib import Path
import cv2,numpy as np
ROOT=Path(__file__).resolve().parents[3]
if str(ROOT) not in sys.path:sys.path.insert(0,str(ROOT))
from bubble_chamber.bitmap_tiles import GrayBMP8,sha256_file
from bubble_chamber.s112_bubble_graph import BubbleConfig,detect_bubble_centers
from scripts.research.bubble_chamber.s113_fullframe_qa import tile_starts,load_keypoints


def operator_protected_mask(shape,marks,xyxy,radius=42):
    mask=np.zeros(shape,np.uint8)
    x0,y0,x1,y1=xyxy
    for m in marks:
        if not m['label'].startswith('f'):continue
        x=int(round(float(m['x_px'])-x0));y=int(round(float(m['y_px'])-y0))
        if -radius<x<shape[1]+radius and -radius<y<shape[0]+radius:
            cv2.circle(mask,(x,y),radius,1,-1)
    return mask.astype(bool)


def tile_pass(gray,marks,xyxy,lsd=None, cfg=BubbleConfig(),view_threshold=.75, preview_side=160):
    src=cv2.morphologyEx(gray,cv2.MORPH_BLACKHAT,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(9,9)))>15
    blocked=operator_protected_mask(gray.shape,marks,xyxy)
    points,detrep=detect_bubble_centers(gray,src,blocked,cfg)
    significant=[p for p in points if p['evidence_score']>=view_threshold]
    h,w=gray.shape
    view=cv2.cvtColor(cv2.resize(gray,(preview_side,preview_side),interpolation=cv2.INTER_AREA),cv2.COLOR_GRAY2BGR)
    for p in significant:
        x=int(round(float(p['x'])/w*preview_side));y=int(round(float(p['y'])/h*preview_side))
        cv2.circle(view,(x,y),1,(8,170,255),-1)
    x0,y0,x1,y1=xyxy
    for k in marks:
        x=float(k['x_px'])-x0;y=float(k['y_px'])-y0
        if not(0<=x<w and 0<=y<h):continue
        cx=int(x/w*preview_side);cy=int(y/h*preview_side)
        color=(210,20,230) if k['label'].startswith('f') else (35,210,35)
        cv2.circle(view,(cx,cy),6,color,1,cv2.LINE_AA)
        cv2.putText(view,k['label'],(cx+4,cy-7),cv2.FONT_HERSHEY_SIMPLEX,.35,color,1)
    safe_points=[{'x_full':round(p['x']+x0,3),'y_full':round(p['y']+y0,3),
                  'x_local':p['x'],'y_local':p['y'],
                  'score_uncalibrated':p['evidence_score'],'dark_contrast':p['dark_contrast'],
                  'coherence':p['coherence'],'morphology_channel':p['morphology_channel'],
                  'candidate_bubble_not_expert_GT':True}
                 for p in significant]
    return view,safe_points,detrep


def process_rows(bmp_path:Path,out_dir:Path,labels:Path|None,
                 tile_size=1024,preview_side=160,threshold=.75,
                 row_start=0,row_end=None):
    if out_dir.resolve()==ROOT.resolve() or ROOT.resolve() in out_dir.resolve().parents:
        raise ValueError('Private photo pixels cannot be exported to the public Git repository')
    out_dir.mkdir(parents=True,exist_ok=True)
    bmp=GrayBMP8(bmp_path);marks=load_keypoints(labels,bmp_path.name,bmp.width,bmp.height)
    xs=tile_starts(bmp.width,tile_size);ys=tile_starts(bmp.height,tile_size)
    end=len(ys) if row_end is None else min(row_end,len(ys))
    if row_start<0 or row_start>=end:raise ValueError('Invalid row range')
    cv2.setNumThreads(1)
    cell=preview_side+22
    for ri in range(row_start,end):
        row_path=out_dir/f'row_R{ri:02d}.jpg'
        rep_path=out_dir/f'row_R{ri:02d}.json'
        if row_path.exists() or rep_path.exists():raise FileExistsError('Already processed row '+str(ri))
        panel=np.full((cell,cell*len(xs),3),245,np.uint8)
        entries=[]
        for ci,x in enumerate(xs):
            y=ys[ri]
            crop,loc=bmp.crop((x+tile_size/2,y+tile_size/2),tile_size)
            view,points,rep=tile_pass(crop,marks,loc.original_xyxy,preview_side=preview_side,view_threshold=threshold)
            px=ci*cell;panel[:preview_side,px:px+preview_side]=view
            cv2.putText(panel,f'R{ri:02d} C{ci:02d}',(px+2,cell-5),cv2.FONT_HERSHEY_SIMPLEX,.37,(0,0,0),1)
            entry={'row':ri,'column':ci,'xyxy_full':loc.original_xyxy,
                  'all_candidate_peaks_not_GT':rep['candidate_dark_centers'],
                  'strong_peak_proposals':len(points),
                  'candidate_coordinates_private':f'candidates_R{ri:02d}_C{ci:02d}.json'}
            entries.append(entry)
            (out_dir/entry['candidate_coordinates_private']).write_text(json.dumps({
                'roi_xyxy_full':loc.original_xyxy,'proposals':points,
                'photometric_source_channel':'MORPH_BLACKHAT_NOT_S88',
                'model':'S112_MULTISCALE_LOG_UNSUPERVISED',
                'physical_particle_identity_verified':False},separators=(',',':')),encoding='utf-8')
        cv2.imwrite(str(row_path),panel,[cv2.IMWRITE_JPEG_QUALITY,88])
        rep_path.write_text(json.dumps({'row':ri,'tiles':entries},ensure_ascii=False,separators=(',',':')),encoding='utf-8')
        print(f'processed row {ri+1}/{len(ys)}',flush=True)
    return {'processed_rows':[row_start,end],'total_rows':len(ys)}


def finalize(bmp_path:Path,out_dir:Path,labels:Path|None,tile_size=1024,preview_side=160,threshold=.75):
    bmp=GrayBMP8(bmp_path);marks=load_keypoints(labels,bmp_path.name,bmp.width,bmp.height)
    xs=tile_starts(bmp.width,tile_size);ys=tile_starts(bmp.height,tile_size)
    row_panels=[];rows=[]
    for ri in range(len(ys)):
        im=cv2.imread(str(out_dir/f'row_R{ri:02d}.jpg'))
        rp=out_dir/f'row_R{ri:02d}.json'
        if im is None or not rp.is_file():raise FileNotFoundError('Incomplete full frame: row '+str(ri))
        row_panels.append(im);rows.extend(json.loads(rp.read_text())['tiles'])
    mosaic=np.vstack(row_panels)
    cv2.imwrite(str(out_dir/'ALL_TILES_S112_PEAKS_UNCALIBRATED_NOT_GT.jpg'),mosaic,[cv2.IMWRITE_JPEG_QUALITY,88])
    summary={'schema':'S113_FULL_FRAME_S112_SOURCE_DERIVED_PEAK_REVIEW',
        'frame_size_wh':[bmp.width,bmp.height],'source_image_sha256':sha256_file(bmp_path),
        'source_name_private':bmp_path.name,'full_frame_tiled_pixel_coverage':True,
        'grid_rows_cols':[len(ys),len(xs)],'tiles_processed':len(rows),
        'total_peak_proposals_including_overlap_duplicates':sum(z['all_candidate_peaks_not_GT'] for z in rows),
        'strong_unverified_candidates_including_overlap_duplicates':sum(z['strong_peak_proposals'] for z in rows),
        'visualization_threshold_uncalibrated':threshold,
        'operator_fiducials':sum(x['label'].startswith('f') for x in marks),
        'operator_start_markers':sum(x['label']=='start' for x in marks),
        'source_mask_is_blackhat_not_S88':True,'trained_ANZA_run':False,
        'S111_global_tracking_run_full_frame':False,'physical_IDs_verified':False,
        'all_outputs_private':True,'tiles':rows}
    (out_dir/'summary_PRIVATE.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2),encoding='utf-8')
    return summary


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--bmp',type=Path,required=True);ap.add_argument('--labels',type=Path)
    ap.add_argument('--private-out',type=Path,required=True)
    ap.add_argument('--tile-size',type=int,default=1024)
    ap.add_argument('--preview-side',type=int,default=160)
    ap.add_argument('--threshold',type=float,default=.75)
    ap.add_argument('--start-row',type=int,default=0)
    ap.add_argument('--end-row',type=int)
    ap.add_argument('--finalize',action='store_true')
    args=ap.parse_args()
    if args.finalize:
        rep=finalize(args.bmp,args.private_out,args.labels,args.tile_size,args.preview_side,args.threshold)
        rep={k:v for k,v in rep.items() if k!='tiles'}
    else:
        rep=process_rows(args.bmp,args.private_out,args.labels,args.tile_size,args.preview_side,args.threshold,args.start_row,args.end_row)
    print(json.dumps(rep,ensure_ascii=False,indent=2))